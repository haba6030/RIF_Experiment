// ============================================================================
// 3. CONDITION ASSIGNMENT (between-subjects valence)
//    P → practice positives (A1, A2, B1, B2)
//    N → practice negatives (A3, A4, B3, B4)
// ============================================================================

const PRACTICE_IDS = {
  P: ['A1', 'A2', 'B1', 'B2'],
  N: ['A3', 'A4', 'B3', 'B4']
};

/**
 * Given a participant condition, return per-item RIF role tag.
 *   RP+  : practiced
 *   RP-  : same set, same valence pair (but unpracticed)
 *   NRP  : neutral baseline (CA1, CB1)
 */
function rifRoleFor(itemId, condition) {
  if (itemId === 'CA1' || itemId === 'CB1') return 'NRP';
  if (PRACTICE_IDS[condition].includes(itemId)) return 'RP+';
  return 'RP-';
}

